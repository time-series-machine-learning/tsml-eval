"""Write a mean-forecast ensemble of existing forecasting result sets.

python combine_forecast_results.py <results_dir> <ensemble_name> <member> [<member> ...]

For every dataset (e.g. M4 series) present in ``<results_dir>/<member>/Predictions``
for ALL members, the members' testResample0 forecasts are averaged and written to
``<results_dir>/<ensemble_name>/Predictions/<dataset>/testResample0.csv`` in the
standard tsml format. Fit/predict times are the sums over members and memory the
maximum, so the cost columns are those of running the members. Series missing from
any member are skipped and counted.
"""

import os
import sys
from datetime import datetime

import numpy as np
from sklearn.metrics import mean_absolute_percentage_error

from tsml_eval.utils.results_writing import write_forecasting_results


def _read(path):
    with open(path) as f:
        lines = f.read().splitlines()
    stats = lines[2].split(",")
    data = np.array([[float(v) for v in l.split(",")[:2]] for l in lines[3:] if l])
    return data[:, 0], data[:, 1], stats


def main(results_dir, name, members):
    datasets = None
    for m in members:
        d = set(os.listdir(f"{results_dir}/{m}/Predictions"))
        datasets = d if datasets is None else datasets & d
    all_d = set().union(
        *(os.listdir(f"{results_dir}/{m}/Predictions") for m in members)
    )
    print(
        f"{len(datasets)} datasets in all members, {len(all_d) - len(datasets)} skipped"
    )

    comment = (
        f"Mean forecast of {members} generated by combine_forecast_results.py on "
        f"{datetime.now().strftime('%m/%d/%Y, %H:%M:%S')}"
    )
    for d in sorted(datasets):
        out = f"{results_dir}/{name}/Predictions/{d}/testResample0.csv"
        if os.path.exists(out):
            continue
        preds, fit, pred_t, mem = [], 0, 0, 0
        for m in members:
            y, p, stats = _read(f"{results_dir}/{m}/Predictions/{d}/testResample0.csv")
            preds.append(p)
            fit += int(float(stats[1]))
            pred_t += int(float(stats[2]))
            mem = max(mem, int(float(stats[4])))
        p = np.mean(preds, axis=0)
        write_forecasting_results(
            p,
            y,
            name,
            d,
            results_dir,
            full_path=False,
            first_line_forecaster_name=f"{name} (mean of {'+'.join(members)})",
            split="TEST",
            random_seed=0,
            time_unit="MILLISECONDS",
            first_line_comment=comment,
            parameter_info=str({"members": members}),
            mape=mean_absolute_percentage_error(y, p),
            fit_time=fit,
            predict_time=pred_t,
            benchmark_time=-1,
            memory_usage=mem,
        )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
