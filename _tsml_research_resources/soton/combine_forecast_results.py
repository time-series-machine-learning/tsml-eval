"""Write a forecast-combination ensemble of existing forecasting result sets.

python combine_forecast_results.py <results_dir> <ensemble_name> <member> [<member> ...]
    [--method mean|median|trim] [--clip-negative] [--datasets PREFIX[,PREFIX...]]

For every dataset (e.g. M4 series) present in ``<results_dir>/<member>/Predictions``
for ALL members, the members' testResample0 forecasts are combined per step and
written to ``<results_dir>/<ensemble_name>/Predictions/<dataset>/testResample0.csv``
in the standard tsml format.

--method        mean (default), median, or trim: the mean after dropping the highest
                and lowest member at each step (plain mean for fewer than 4 members).
--clip-negative replace negative combined forecasts with 0 (as SCUM does for M4).
--datasets      only combine datasets whose name starts with one of these prefixes,
                e.g. ``m4_yearly_dataset``, so different frequencies can use different
                members under one ensemble name.

Fit/predict times are the sums over members and memory the maximum, so the cost
columns are those of running the members. Series missing from any member are skipped
and counted. Existing output files are left as they are.
"""

import argparse
import os
from datetime import datetime

import numpy as np
from sklearn.metrics import mean_absolute_percentage_error

from tsml_eval.utils.results_writing import write_forecasting_results


def _read(path):
    with open(path) as f:
        lines = f.read().splitlines()
    stats = lines[2].split(",")
    data = np.array([[float(v) for v in l.split(",")[:2]] for l in lines[3:] if l])
    return data[:, 0], data[:, 1], stats


def combine(preds, method="mean"):
    """Combine member forecasts, shape (n_members, horizon), per step."""
    preds = np.asarray(preds, dtype=float)
    if method == "mean":
        return preds.mean(axis=0)
    if method == "median":
        return np.median(preds, axis=0)
    if method == "trim":
        k = preds.shape[0]
        if k < 4:
            return preds.mean(axis=0)
        return (preds.sum(axis=0) - preds.max(axis=0) - preds.min(axis=0)) / (k - 2)
    raise ValueError(f"unknown method {method!r}")


def main(results_dir, name, members, method="mean", clip_negative=False, prefixes=None):
    datasets = None
    for m in members:
        d = set(os.listdir(f"{results_dir}/{m}/Predictions"))
        datasets = d if datasets is None else datasets & d
    all_d = set().union(
        *(os.listdir(f"{results_dir}/{m}/Predictions") for m in members)
    )
    if prefixes:
        datasets = {d for d in datasets if d.startswith(tuple(prefixes))}
        all_d = {d for d in all_d if d.startswith(tuple(prefixes))}
    print(
        f"{len(datasets)} datasets in all members, {len(all_d) - len(datasets)} skipped"
    )

    label = f"{method} of {'+'.join(members)}" + (", clipped at 0" if clip_negative else "")
    comment = (
        f"Forecast combination ({label}) generated by combine_forecast_results.py on "
        f"{datetime.now().strftime('%m/%d/%Y, %H:%M:%S')}"
    )
    for d in sorted(datasets):
        out = f"{results_dir}/{name}/Predictions/{d}/testResample0.csv"
        if os.path.exists(out):
            continue
        preds, fit, pred_t, mem = [], 0, 0, 0
        for m in members:
            y, p, stats = _read(f"{results_dir}/{m}/Predictions/{d}/testResample0.csv")
            preds.append(p)
            fit += int(float(stats[1]))
            pred_t += int(float(stats[2]))
            mem = max(mem, int(float(stats[4])))
        p = combine(preds, method)
        if clip_negative:
            p = np.maximum(p, 0.0)
        write_forecasting_results(
            p,
            y,
            name,
            d,
            results_dir,
            full_path=False,
            first_line_forecaster_name=f"{name} ({label})",
            split="TEST",
            random_seed=0,
            time_unit="MILLISECONDS",
            first_line_comment=comment,
            parameter_info=str(
                {"members": members, "method": method, "clip_negative": clip_negative}
            ),
            mape=mean_absolute_percentage_error(y, p),
            fit_time=fit,
            predict_time=pred_t,
            benchmark_time=-1,
            memory_usage=mem,
        )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("results_dir")
    parser.add_argument("name")
    parser.add_argument("members", nargs="+")
    parser.add_argument("--method", default="mean", choices=["mean", "median", "trim"])
    parser.add_argument("--clip-negative", action="store_true")
    parser.add_argument("--datasets", default=None)
    a = parser.parse_args()
    main(
        a.results_dir,
        a.name,
        a.members,
        a.method,
        a.clip_negative,
        a.datasets.split(",") if a.datasets else None,
    )
